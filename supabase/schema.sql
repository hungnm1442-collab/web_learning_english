-- 1. Bảng hồ sơ người học
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Người học',
  level text not null default 'A1-A2',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. Bảng lưu trạng thái học tập đồng bộ theo từng tài khoản
-- Lưu: tiến độ 10 bài học, hệ thống flashcard 6 hộp (SRS), chuỗi ngày (streak),
-- mục tiêu mỗi ngày, điểm phát âm cao nhất và cài đặt cá nhân.
create table if not exists public.user_state (
  user_id uuid primary key references auth.users(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- 3. Bảng danh mục từ vựng & tiến độ từng từ (mở rộng / tra cứu phía server)
create table if not exists public.vocabulary_words (
  id bigint generated by default as identity primary key,
  word text not null unique,
  meaning text not null,
  word_type text not null,
  pronunciation text,
  example text,
  created_at timestamptz not null default now()
);

create table if not exists public.user_word_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  word_id bigint not null references public.vocabulary_words(id) on delete cascade,
  review_count integer not null default 0 check (review_count >= 0),
  last_reviewed_at timestamptz,
  remembered boolean not null default false,
  primary key (user_id, word_id)
);

-- 4. Bảng danh mục bài học & tiến độ từng bài học
create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  title text not null,
  subtitle text not null,
  category text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.lesson_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  progress integer not null default 0 check (progress between 0 and 100),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, lesson_id)
);

-- ============================================================================
-- ROW LEVEL SECURITY (RLS) - CÔ LẬP DỮ LIỆU GIỮA CÁC TÀI KHOẢN
-- ============================================================================

alter table public.profiles enable row level security;
alter table public.user_state enable row level security;
alter table public.vocabulary_words enable row level security;
alter table public.user_word_progress enable row level security;
alter table public.lessons enable row level security;
alter table public.lesson_progress enable row level security;

-- Policies cho bảng profiles
drop policy if exists "Profiles are readable by their owner" on public.profiles;
create policy "Profiles are readable by their owner"
  on public.profiles for select using (auth.uid() = id);

drop policy if exists "Users can create their own profile" on public.profiles;
create policy "Users can create their own profile"
  on public.profiles for insert with check (auth.uid() = id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update using (auth.uid() = id);

-- Policies cho bảng user_state
drop policy if exists "Users can manage their own learning state" on public.user_state;
create policy "Users can manage their own learning state"
  on public.user_state for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Policies cho bảng vocabulary_words & user_word_progress
drop policy if exists "Vocabulary is readable by signed-in users" on public.vocabulary_words;
create policy "Vocabulary is readable by signed-in users"
  on public.vocabulary_words for select to authenticated using (true);

drop policy if exists "Users can manage their own word progress" on public.user_word_progress;
create policy "Users can manage their own word progress"
  on public.user_word_progress for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Policies cho bảng lessons & lesson_progress
drop policy if exists "Lessons are readable by signed-in users" on public.lessons;
create policy "Lessons are readable by signed-in users"
  on public.lessons for select to authenticated using (true);

drop policy if exists "Users can manage their own lesson progress" on public.lesson_progress;
create policy "Users can manage their own lesson progress"
  on public.lesson_progress for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- ============================================================================
-- TRIGGER TỰ ĐỘNG KHỞI TẠO HỒ SƠ & TIẾN ĐỘ CHO TÀI KHOẢN MỚI
-- ============================================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(split_part(new.email, '@', 1), 'Người học')
  )
  on conflict (id) do nothing;

  insert into public.user_state (user_id, data)
  values (new.id, '{}'::jsonb)
  on conflict (user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

